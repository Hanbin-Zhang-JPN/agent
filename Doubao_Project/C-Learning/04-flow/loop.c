/* ============================================================
 * 文件：04-flow/loop.c
 * 主题：循环
 * 学习点：for / while / do-while / break / continue
 * ============================================================ */

#include <stdio.h>                 // 引入标准输入输出库

int main(void)
{
    // 1. for 循环：适合"知道循环次数"的场景
    // 结构：初始化 ; 条件 ; 每次循环后执行的操作
    for (int i = 1; i <= 5; i++) { // i 从 1 到 5，一共循环 5 次
        printf("第 %d 次\n", i);   // 打印当前的 i
    }

    // 2. while 循环：适合"不知道次数、只看条件"的场景
    int n = 1;                     // 循环变量初始值
    while (n <= 3) {               // 条件成立就继续循环
        printf("n = %d\n", n);     // 打印当前的 n
        n++;                       // 每次让 n 加 1，否则会死循环
    }

    // 3. do-while 循环：无论条件如何，至少执行一次
    int m = 10;                    // 初始值不满足下面的条件
    do {
        printf("m = %d\n", m);     // 先执行一次
        m++;                       // m 变为 11
    } while (m < 3);               // 条件不成立，循环结束

    // 4. continue：跳过本次循环剩余代码，进入下一次
    for (int i = 1; i <= 10; i++) {
        if (i == 3) {              // i 等于 3 时
            continue;              // 跳过后面的打印，直接进入 i = 4
        }
        if (i == 6) {              // i 等于 6 时
            break;                 // 终止整个循环
        }
        printf("i = %d\n", i);     // 实际会打印 1 2 4 5
    }

    return 0;                      // 程序正常结束
}                                  // main 函数结束
