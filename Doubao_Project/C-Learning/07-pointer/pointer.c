#include <stdio.h>                 // 引入标准输入输出库

// 交换函数：用指针才能修改到外面的变量
// 如果只传值，函数内部换完就丢了，外面不变
void swap(int *x, int *y)          // 参数是指针，存的是地址
{
    int temp = *x;                 // 先把 x 指向的值存到临时变量
    *x = *y;                       // 把 y 指向的值赋给 x 指向的变量
    *y = temp;                     // 再把临时值赋给 y 指向的变量
}                                  // swap 函数结束

int main(void)
{
    // 1. 什么是指针：指针是"存放地址的变量"
    int num = 42;                  // 普通变量，在内存中占一块空间
    int *p = &num;                 // p 存 num 的地址，& 是取地址运算符

    // 2. 用 * 解引用：通过指针访问它指向的变量
    printf("num 的值：%d\n", num);     // 直接访问，得到 42
    printf("p 指向的值：%d\n", *p);    // 通过指针访问，结果一样

    // 3. 通过指针修改指向的变量
    *p = 99;                       // 相当于 num = 99
    printf("修改后 num = %d\n", num);   // 输出 99

    // 4. 指针与数组：数组名就是首元素的地址
    int arr[3] = {10, 20, 30};     // 普通数组
    int *pa = arr;                 // 等价于 &arr[0]，指向第一个元素
    printf("第一个元素：%d\n", *pa);       // 解引用得到 10
    printf("第二个元素：%d\n", *(pa + 1)); // 指针加 1 跳到下一个元素，得到 20

    // 5. 指针做函数参数：把地址传进去，函数内部才能改外面的值
    int m = 5, k = 8;              // 两个待交换的变量
    swap(&m, &k);                  // 传地址给 swap
    printf("交换后 m = %d, k = %d\n", m, k);   // 输出 8 和 5

    return 0;                      // 程序正常结束
}                                  // main 函数结束
