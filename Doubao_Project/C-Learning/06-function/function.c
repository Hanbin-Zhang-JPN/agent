#include <stdio.h>                 // 引入标准输入输出库

// 函数定义格式：返回类型 函数名(参数列表) { 函数体 }
// 这个函数接收两个整数，返回它们的和
int add(int a, int b)              // 返回类型是 int
{
    int result = a + b;            // 计算两数之和
    return result;                 // return 把结果交回给调用处
}                                  // add 函数结束

// 没有返回值的函数：返回类型写 void
void sayHello(void)                // void 表示不接收参数
{
    printf("你好！\n");            // 函数体：只做一件事
}                                  // sayHello 函数结束

// 演示"值传递"：函数内部修改形参，不影响外面的变量
int doubleIt(int n)                // n 是外面的实参的"副本"
{
    n = n * 2;                     // 修改的是副本 n
    return n;                      // 把新值返回出去
}                                  // doubleIt 函数结束

int main(void)
{
    // 1. 调用带返回值的函数
    int s = add(3, 5);             // 把 3 和 5 传给 add，返回值存入 s
    printf("3 + 5 = %d\n", s);     // 输出 8

    // 2. 调用无返回值的函数
    sayHello();                    // 直接调用，不需要接收返回值

    // 3. 观察值传递：外面变量不受函数内部影响
    int x = 10;                    // 外面定义变量 x
    int y = doubleIt(x);           // 把 x 传进去，函数内部翻倍后返回
    printf("x 仍然是 %d，翻倍结果是 %d\n", x, y);   // 输出 10 和 20

    return 0;                      // 程序正常结束
}                                  // main 函数结束
