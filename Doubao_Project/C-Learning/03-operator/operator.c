/* ============================================================
 * 文件：03-operator/operator.c
 * 主题：常用运算符
 * 学习点：算术 / 自增 / 关系 / 逻辑 / 赋值运算符
 * ============================================================ */

#include <stdio.h>                 // 引入标准输入输出库

int main(void)
{
    // 1. 算术运算符
    int a = 10, b = 3;             // 准备两个整数
    printf("10 + 3 = %d\n", a + b);   // 加法，结果是 13
    printf("10 - 3 = %d\n", a - b);   // 减法，结果是 7
    printf("10 * 3 = %d\n", a * b);   // 乘法，结果是 30
    printf("10 / 3 = %d\n", a / b);   // 除法：整数除以整数得到 3（小数被丢弃）
    printf("10 %% 3 = %d\n", a % b);  // 取余：10 除以 3 余 1
    // 注意：printf 里想输出 % 本身，必须写成 %%

    // 2. 自增与自减
    int c = 5;                     // 初始值 5
    c++;                           // 自增：相当于 c = c + 1
    printf("自增后 c = %d\n", c);  // 结果是 6

    // 3. 关系运算符：成立返回 1（真），不成立返回 0（假）
    printf("a > b ? %d\n", a > b);     // 10 > 3 成立，输出 1
    printf("a == b ? %d\n", a == b);   // 10 == 3 不成立，输出 0

    // 4. 逻辑运算符
    int x = 1, y = 0;              // 用 1 和 0 表示真和假
    printf("x && y = %d\n", x && y);   // && 与：两个都真才为真，输出 0
    printf("x || y = %d\n", x || y);   // || 或：有一个真就为真，输出 1
    printf("!x     = %d\n", !x);       // ! 非：真变假、假变真，输出 0

    // 5. 复合赋值运算符
    int n = 5;                     // 初始值 5
    n += 3;                        // 相当于 n = n + 3
    printf("n = %d\n", n);         // 结果是 8

    return 0;                      // 程序正常结束
}                                  // main 函数结束
