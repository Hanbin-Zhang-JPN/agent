/* ============================================================
 * 文件：02-variable/variable.c
 * 主题：变量的声明、赋值与使用
 * 学习点：声明变量 / 重新赋值 / 一次声明多个 / printf 占位符
 * ============================================================ */

#include <stdio.h>                 // 引入标准输入输出库

int main(void)
{
    // 1. 声明变量：先写类型，再写名字
    int age = 20;                  // 整型变量 age，初始值是 20

    // 2. 变量可以被重新赋值
    age = 21;                      // 把 21 存进 age，覆盖原来的 20

    // 3. 一条语句声明多个同类型变量
    int a = 1, b = 2;              // 多个变量用逗号隔开，写在同一个分号前

    // 4. 输出变量的值：%d 是整数占位符，会被对应变量替换
    printf("年龄：%d\n", age);     // 输出：年龄：21

    // 5. 多个占位符按顺序对应后面的变量
    printf("a = %d, b = %d\n", a, b);   // 输出：a = 1, b = 2

    return 0;                      // 程序正常结束
}                                  // main 函数结束
