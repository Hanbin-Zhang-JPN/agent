/* ============================================================
 * 文件：01-hello/hello.c
 * 主题：第一个 C 程序
 * 学习点：main 入口 / printf 输出 / return 返回
 * ============================================================ */

#include <stdio.h>                 // 引入标准输入输出库，printf 靠它工作

// main 是程序入口，程序一运行就从这里开始执行
int main(void)                     // void 表示 main 不需要接收参数
{
    printf("你好，C 语言！\n");    // printf 负责打印文字，\n 是换行符
    return 0;                      // 返回 0 表示程序正常结束
}                                  // main 函数结束
