#!/bin/bash
# ============================================================
# 一键编译脚本：把 src 下所有 .java 源文件编译到 out 目录
# 用法：./compile.sh
# 说明：-encoding UTF-8 保证中文注释不乱码；-d out 指定输出目录
# ============================================================

# 进入脚本所在目录，保证在任何位置执行路径都正确
cd "$(dirname "$0")"

# 编译所有源码；find 递归找出 src 下的全部 .java 文件
javac -encoding UTF-8 -d out $(find src -name "*.java")

# $? 是上一条命令的退出码，0 表示成功
if [ $? -eq 0 ]; then
    echo "✔ 编译成功，字节码已输出到 out/ 目录"
else
    echo "✘ 编译失败，请检查上面的报错信息"
fi
